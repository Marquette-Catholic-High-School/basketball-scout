"""Render a ScoutingReport as Markdown (download / print / paste into a doc)."""

from __future__ import annotations

import re
from datetime import date

from scout.schemas import Game, KeyPlayer, PlayTendency, ScoutingReport

# A line starting with one of these would turn into a heading, quote or list item.
_BLOCK_START = re.compile(r"^(#{1,6}|>|[-+*]|\d+[.)])(?=\s|$)")


def _escape_marker(match: re.Match[str]) -> str:
    marker = match.group(1)
    if marker[0].isdigit():  # "3." -> "3\." (a backslash only escapes punctuation)
        return f"{marker[:-1]}\\{marker[-1]}"
    return f"\\{marker}"


def _inline(text: str) -> str:
    """One line of plain text, safe to place at the start of a Markdown line or list item."""
    line = " ".join(text.split())
    return _BLOCK_START.sub(_escape_marker, line)


def _cell(text: str) -> str:
    return _inline(text).replace("|", "\\|")


def _paragraphs(text: str) -> str:
    """Keep the model's paragraph breaks; collapse everything else."""
    paragraphs = [_inline(p) for p in re.split(r"\n\s*\n", text.strip())]
    return "\n\n".join(p for p in paragraphs if p)


def _long_date(value: date) -> str:
    return f"{value:%B} {value.day}, {value.year}"


def _subtitle(game: Game) -> str:
    matchup = f"{game.scouted_team} vs {game.other_team}" if game.other_team else game.scouted_team
    details = [game.title, _long_date(game.game_date) if game.game_date else None, game.level, game.location]
    return " · ".join([f"**Film:** {_inline(matchup)}", *(_inline(d) for d in details if d)])


def _bullets(title: str, items: list[str], *, numbered: bool = False) -> list[str]:
    lines = [_inline(item) for item in items if item.strip()]
    if not lines:
        return []
    body = "\n".join(f"{i}. {line}" if numbered else f"- {line}" for i, line in enumerate(lines, start=1))
    return [f"## {title}", body]


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_cell(value) for value in row) + " |" for row in rows]
    return "\n".join(lines)


def _key_players(players: list[KeyPlayer]) -> list[str]:
    if not players:
        return []
    rows = [
        [
            p.jersey.strip().lstrip("#"),
            p.name,
            p.role,
            p.threat_level.capitalize(),
            "; ".join(p.strengths),
            "; ".join(p.weaknesses),
            p.how_to_defend,
        ]
        for p in players
    ]
    header = ["#", "Player", "Role", "Threat", "Strengths", "Weaknesses", "How to defend"]
    return ["## Key Players", _table(header, rows)]


def _play_tendencies(tendencies: list[PlayTendency]) -> list[str]:
    if not tendencies:
        return []
    rows = [[t.play_type, t.frequency, t.effectiveness, t.counter] for t in tendencies]
    return ["## Play Tendencies", _table(["Play type", "Frequency", "Effectiveness", "Counter"], rows)]


def report_to_markdown(report: ScoutingReport, game: Game, *, model: str | None = None) -> str:
    """A coach-ready document: title, headline, summary, keys, personnel, offense, defense, plans, caveats.

    Empty sections are left out. The footer names the model and reminds the reader that
    the numbers come from video analysis.
    """
    blocks = [
        f"# Scouting Report: {_inline(game.scouted_team)}",
        _subtitle(game),
        f"> **{_inline(report.headline)}**",
        "## Summary",
        _paragraphs(report.executive_summary),
        *_bullets("Keys to Win", report.keys_to_win, numbered=True),
        *_key_players(report.key_players),
        *_bullets("Offensive Identity", report.offensive_identity),
        *_play_tendencies(report.play_tendencies),
        *_bullets("Transition", report.transition),
        *_bullets("Defensive Identity", report.defensive_identity),
        *_bullets("Special Situations", report.special_situations),
        *_bullets("Defensive Game Plan", report.defensive_game_plan),
        *_bullets("Offensive Game Plan", report.offensive_game_plan),
        *_bullets("Practice Emphasis", report.practice_emphasis),
        *_bullets("Data Caveats", report.data_caveats),
        "---",
        f"_Generated by {_inline(model or 'Claude')} from video analysis - verify against film._",
    ]
    return "\n\n".join(block for block in blocks if block) + "\n"
